import { beforeEach, expect, it, vi } from 'vitest'
const mocks = vi.hoisted(() => ({ requireUser: vi.fn(), circle: vi.fn(), favors: vi.fn(), overview: vi.fn(), balancesFor: vi.fn() }))
vi.mock('../lib/auth-session', () => ({ requireUser: mocks.requireUser }))
vi.mock('../lib/circle-data', () => ({ getCircleSummary: mocks.circle }))
vi.mock('../lib/favor-data', () => ({ getFavorSummary: mocks.favors }))
vi.mock('../lib/ledger-data', () => ({ getLedgerOverview: mocks.overview }))
vi.mock('../lib/ledger-service', () => ({ createLedgerService: () => ({ balancesFor: mocks.balancesFor }) }))
vi.mock('../lib/db', () => ({ getPrisma: () => ({}) }))
vi.mock('../app/dashboard/dashboard-client', () => ({ default: () => null }))
import DashboardPage from '../app/dashboard/page'

beforeEach(() => vi.resetAllMocks())
it('connects session-scoped summaries and balances while omitting friends’ private email', async () => {
  mocks.requireUser.mockResolvedValue({ id: 'actor', name: 'Owner', email: 'owner@example.invalid' })
  mocks.circle.mockResolvedValue({ accepted: 1, incoming: 2, unread: 3, preview: [{ id: 'connection', person: { id: 'friend', name: 'Friend', email: 'private@example.invalid' } }] })
  mocks.favors.mockResolvedValue({ confirmed: 9, pending: 2, awaiting: 1 })
  mocks.overview.mockResolvedValue({ summary: { owedToMe: 4, iOwe: 2 }, preview: [], recent: [] })
  mocks.balancesFor.mockResolvedValue([{ person: { id: 'friend' }, balance: 4 }])
  const page = await DashboardPage()
  expect(mocks.circle).toHaveBeenCalledWith('actor')
  expect(mocks.favors).toHaveBeenCalledWith('actor')
  expect(mocks.overview).toHaveBeenCalledWith('actor')
  expect(mocks.balancesFor).toHaveBeenCalledWith('actor', ['friend'])
  expect(page.props.circleBalances).toEqual({ friend: 4 })
  expect(page.props.ledger.summary).toEqual({ owedToMe: 4, iOwe: 2 })
  expect(page.props.summary.preview[0].person.email).toBeNull()
  expect(page.props.user.email).toBe('owner@example.invalid')
  expect(Number.isNaN(Date.parse(page.props.now))).toBe(false)
})
